#!/usr/bin/env bash
# Run AFTER the Quattro upgrade + reboot, from inside the new session.
#
# Installs the ported Hyprland Lua configs over the Quattro defaults the upgrade
# dropped into the stowed tree, retires the config packages Quattro no longer
# reads, and re-applies the dynamic theme so the new templates regenerate.
#
# Nothing here is destructive to the git repo: retired files are moved into
# quattro/legacy/ rather than deleted, so `git status` shows exactly what moved.
set -uo pipefail

DOTFILES="${DOTFILES:-$HOME/.dotfiles}"
HERE="$DOTFILES/quattro"
LEGACY="$HERE/legacy"

say() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[33m    ! %s\033[0m\n' "$*"; }

say "Sanity check"
ver=$(omarchy version 2>/dev/null | grep -oE '^[0-9]+' || echo 0)
if [ "${ver:-0}" -lt 4 ]; then
  warn "omarchy reports version '$(omarchy version 2>/dev/null)' -- expected 4.x."
  warn "Run this only after the Quattro upgrade and a reboot."
  exit 1
fi
echo "  omarchy $(omarchy version)"
[ -d /usr/share/hypr/stubs ] && echo "  hyprland lua stubs present"

say "Installing ported Hyprland Lua configs"
# ~/.config/hypr is a stow symlink, so these writes land in the repo and stay
# stowed. The upgrade already backed up whatever was there as *.bak.
for f in monitors.lua input.lua bindings.lua looknfeel.lua autostart.lua; do
  if [ -f "$HERE/hypr/$f" ]; then
    cp -f "$HERE/hypr/$f" "$HOME/.config/hypr/$f" && echo "  installed $f"
  fi
done

say "Retiring configs Quattro no longer reads"
mkdir -p "$LEGACY/hypr" "$LEGACY/themed"

# Legacy Hyprland .conf entry points. The upgrade deliberately leaves these in
# place for reference; Quattro's hyprland.lua never sources them.
for f in hyprland.conf bindings.conf autostart.conf looknfeel.conf monitors.conf \
         input.conf envs.conf hyprlock.conf hypridle.conf; do
  src="$DOTFILES/hypr/.config/hypr/$f"
  [ -f "$src" ] && { git -C "$DOTFILES" mv -k "hypr/.config/hypr/$f" "quattro/legacy/hypr/$f" 2>/dev/null \
    || mv -f "$src" "$LEGACY/hypr/$f"; echo "  retired hypr/$f"; }
done

# waybar.css.tpl targets a bar that no longer exists; hyprland.conf.tpl is
# superseded by Quattro's hyprland.lua.tpl, and the gradient it produced now
# comes from the hyprland_active_border key that wallpaper-palette writes
# straight into colors.toml.
for f in waybar.css.tpl hyprland.conf.tpl; do
  src="$DOTFILES/omarchy/.config/omarchy/themed/$f"
  [ -f "$src" ] && { mv -f "$src" "$LEGACY/themed/$f"; echo "  retired themed/$f"; }
done

# Whole stow packages for retired apps.
for pkg in waybar walker mako swayosd; do
  [ -d "$DOTFILES/$pkg" ] && { mkdir -p "$LEGACY"; mv -f "$DOTFILES/$pkg" "$LEGACY/$pkg"; echo "  retired stow package $pkg"; }
done

# Retired systemd user units (the upgrade already removed the live symlinks).
for u in swayosd-server.service elephant.service; do
  f="$DOTFILES/systemd/.config/systemd/user/$u"
  [ -f "$f" ] && { mkdir -p "$LEGACY/systemd"; mv -f "$f" "$LEGACY/systemd/$u"; echo "  retired systemd/$u"; }
done
d="$DOTFILES/systemd/.config/systemd/user/app-walker@autostart.service.d"
[ -d "$d" ] && { mkdir -p "$LEGACY/systemd"; mv -f "$d" "$LEGACY/systemd/"; echo "  retired systemd/app-walker@autostart.service.d"; }

say "Updating .gitignore for the moved theme state"
gi="$DOTFILES/.gitignore"
if grep -q 'omarchy/.config/omarchy/current/' "$gi" 2>/dev/null; then
  python3 - "$gi" <<'PY'
import sys, pathlib
p = pathlib.Path(sys.argv[1])
s = p.read_text()
s = s.replace(
    "# Omarchy machine state — regenerated by `omarchy theme set`, never commit\nomarchy/.config/omarchy/current/",
    "# Omarchy machine state. Omarchy 4 generates this into ~/.local/state/omarchy/current,\n"
    "# outside the stowed tree, so nothing lands in the repo any more. Kept for old checkouts.\n"
    "omarchy/.config/omarchy/current/",
)
p.write_text(s)
PY
  echo "  annotated."
fi

say "Re-stowing"
(cd "$DOTFILES" && stow -R bin hypr omarchy ghostty systemd) && echo "  done."

say "Regenerating the dynamic theme with Quattro's templates"
if dynamic-theme; then
  echo "  ok."
else
  warn "dynamic-theme failed (offline?). Run it again later, or: omarchy theme set dynamic"
fi

say "Validating the Hyprland config"
hyprctl reload >/dev/null 2>&1
errors=$(hyprctl configerrors 2>&1)
if [ -z "$errors" ] || [ "$errors" = "no errors" ]; then
  echo "  no errors."
else
  warn "hyprctl configerrors reported:"
  printf '%s\n' "$errors"
fi

say "Left to check by hand"
cat <<'TODO'
  - Bar layout: Quattro has ONE bar position for all monitors. The old
    DP-2-on-top / HDMI-A-1-on-bottom split has no stock equivalent.
      omarchy bar position top
    Custom cpu-temp / gpu-temp / voxtype widgets need porting as shell plugins:
      omarchy plugin clone omarchy.<widget>   # then edit ~/.config/omarchy/plugins/
  - Wi-Fi: if any saved networks are missing, re-add them via the shell's
    network panel (the iwd profiles were not converted).
  - Review and commit:  git -C ~/.dotfiles status
TODO
